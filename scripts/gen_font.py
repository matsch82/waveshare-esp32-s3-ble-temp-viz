#!/usr/bin/env python3
"""Generate a 1-bpp LVGL font with only the glyphs needed for big numbers.

LVGL's built-in Montserrat stops at 48 px. This renders the same
Montserrat-Medium.ttf (shipped with the LVGL component) at a larger size,
thresholded to 1 bpp exactly like the e-paper framebuffer, so no external
font converter is needed.

Usage: python3 scripts/gen_font.py [size]   (default 64)
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = ROOT / "managed_components" / "lvgl__lvgl" / "scripts" / "generators" / "built_in_font" / "Montserrat-Medium.ttf"
ASSETS = ROOT / "main" / "assets"

# One contiguous range keeps the cmap trivial: "-", ".", "/", "0".."9", ":".
FIRST, LAST = ord("-"), ord(":")


def render_glyph(font: ImageFont.FreeTypeFont, ch: str):
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    bits: list[int] = []
    if w and h:
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        bits = [1 if img.getpixel((x, y)) >= 128 else 0 for y in range(h) for x in range(w)]
    return {
        "adv_w": round(font.getlength(ch) * 16),
        "box_w": w,
        "box_h": h,
        "ofs_x": x0,
        "ofs_y": -y1,
        "bits": bits,
    }


def pack(bits: list[int]) -> bytes:
    """Rows packed back to back, MSB first (LVGL fmt_txt with stride 0)."""
    out = bytearray()
    for i in range(0, len(bits), 8):
        byte = 0
        for j, b in enumerate(bits[i:i + 8]):
            if b:
                byte |= 0x80 >> j
        out.append(byte)
    return bytes(out)


def main() -> None:
    size = int(sys.argv[1]) if len(sys.argv) > 1 else 64
    if not TTF.exists():
        sys.exit(f"{TTF} not found; run a build first so the LVGL component is fetched.")
    font = ImageFont.truetype(str(TTF), size)
    ascent, descent = font.getmetrics()
    name = f"font_digits_{size}"

    glyphs = [render_glyph(font, chr(c)) for c in range(FIRST, LAST + 1)]
    bitmap = bytearray()
    dsc_lines = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,"]
    for c, g in zip(range(FIRST, LAST + 1), glyphs):
        dsc_lines.append(
            f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {g['adv_w']}, .box_w = {g['box_w']}, "
            f".box_h = {g['box_h']}, .ofs_x = {g['ofs_x']}, .ofs_y = {g['ofs_y']}}}, /* '{chr(c)}' */"
        )
        bitmap += pack(g["bits"])

    cap_height = -font.getbbox("0", anchor="ls")[1]
    x_height = -font.getbbox("x", anchor="ls")[1]
    hex_rows = [", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) for i in range(0, len(bitmap), 16)]

    src = f"""/* Generated by scripts/gen_font.py from Montserrat-Medium.ttf ({size} px, 1 bpp).
   Glyphs: '-' '.' '/' '0'..'9' ':'. Do not edit by hand. */
#include "lvgl.h"

static const uint8_t glyph_bitmap[] = {{
    {(","+chr(10)+"    ").join(hex_rows)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(dsc_lines)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{
        .range_start = {FIRST}, .range_length = {LAST - FIRST + 1}, .glyph_id_start = 1,
        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
        .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY
    }}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 1,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .cap_height = {cap_height},
    .x_height = {x_height},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = {-round(size / 12)},
    .underline_thickness = {max(1, round(size / 24))},
    .static_bitmap = 1,
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};
"""
    (ASSETS / f"{name}.c").write_text(src)
    widths = {chr(c): g["adv_w"] / 16 for c, g in zip(range(FIRST, LAST + 1), glyphs)}
    print(f"wrote {name}.c: {len(bitmap)} bitmap bytes, line height {ascent + descent}")
    for sample in ("24.8", "-12.5", "38.8", "20:08", "00:00"):
        print(f"  '{sample}' = {sum(widths[ch] for ch in sample):.0f} px")


if __name__ == "__main__":
    main()
